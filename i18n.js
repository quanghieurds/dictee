  const KEY = 'dictee.lang';
  let lang = 'vi';
  try { if (DICT[localStorage.getItem(KEY)]) lang = localStorage.getItem(KEY); } catch { /* bỏ qua */ }

  function t(key, params) {
    let s = DICT[lang][key] ?? DICT.vi[key] ?? key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
    return s;
  }

  // Dịch các phần tử tĩnh có data-i18n / data-i18n-ph / data-i18n-title.
  function apply(root = document) {
    document.documentElement.lang = lang;
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  }

  function setLang(l) {
    if (!DICT[l]) return;
    lang = l;
    try { localStorage.setItem(KEY, l); } catch { /* bỏ qua */ }
    apply();
  }

  window.DicteeI18n = { t, apply, setLang, get lang() { return lang; } };
